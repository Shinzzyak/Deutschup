#!/usr/bin/env node
/**
 * Merge vocabulary sources - FINAL VERSION
 */

const fs = require('fs');
const path = require('path');

const VOCAB_FILE = path.join(__dirname, '../src/data/vocabulary.ts');
const COMMON_FILE = path.join(__dirname, '../src/data/common-vocabulary.ts');
const OUTPUT_FILE = path.join(__dirname, '../src/data/vocabulary.ts');

// Parse vocabularyData using Function constructor
function parseVocabData(content) {
  const match = content.match(/vocabularyData: VocabWord\[\] = \[([\s\S]*?)\];/);
  if (!match) return [];
  
  try {
    const fn = new Function('return [' + match[1] + ']');
    return fn();
  } catch (e) {
    console.error('Failed to parse vocabularyData:', e.message);
    return [];
  }
}

// Parse commonVocabulary using Function constructor
function parseCommonData(content) {
  const match = content.match(/commonVocabulary = \[([\s\S]*?)\];/);
  if (!match) return [];
  
  try {
    const fn = new Function('return [' + match[1] + ']');
    return fn();
  } catch (e) {
    console.error('Failed to parse commonVocabulary:', e.message);
    return [];
  }
}

// Read files FIRST
console.log('Reading files...');
const vocabContent = fs.readFileSync(VOCAB_FILE, 'utf8');
const commonContent = fs.readFileSync(COMMON_FILE, 'utf8');

const lessonEntries = parseVocabData(vocabContent);
const commonEntries = parseCommonData(commonContent);

console.log(`Lesson vocabulary: ${lessonEntries.length} entries`);
console.log(`Common vocabulary: ${commonEntries.length} entries`);

// Merge and deduplicate by German word
const merged = new Map();

// Add lesson vocabulary first (source of truth)
lessonEntries.forEach(v => {
  const key = v.word.toLowerCase();
  if (!merged.has(key)) {
    merged.set(key, v);
  }
});

// Add common vocabulary (skip if already exists)
commonEntries.forEach(v => {
  const key = v.german.toLowerCase();
  if (!merged.has(key)) {
    merged.set(key, {
      id: `v-common-${merged.size + 1}`,
      word: v.german,
      translation: v.indonesian,
      exampleSentence: '',
      phonetic: '',
      level: v.level,
      theme: 'Common Vocabulary',
      chapter: 0,
      type: 'other'
    });
  }
});

const finalVocab = Array.from(merged.values());
console.log(`Merged vocabulary: ${finalVocab.length} entries`);

// Generate TypeScript file
const tsContent = `import { VocabWord } from './course';

export interface VocabWord {
  id: string;
  word: string;
  translation: string;
  exampleSentence: string;
  phonetic: string;
  level: string;
  theme: string;
  chapter: number;
  type: string;
}

// Auto-generated by merge-vocabulary.cjs
// Sources: Lesson vocabulary (${lessonEntries.length}) + Common vocabulary (${commonEntries.length})
// Total: ${finalVocab.length} unique entries
// Generated: ${new Date().toISOString()}

export const vocabularyData: VocabWord[] = [
${finalVocab.map(v => `  {
    id: "${v.id}",
    word: "${v.word.replace(/"/g, '\\"')}",
    translation: "${v.translation.replace(/"/g, '\\"')}",
    exampleSentence: "${v.exampleSentence || ''}",
    phonetic: "${v.phonetic || ''}",
    level: "${v.level}",
    theme: "${v.theme || 'General'}",
    chapter: ${v.chapter || 0},
    type: "${v.type || 'other'}"
  }`).join(',\n')}
];

export const vocabularyByLevel = {
  A1: vocabularyData.filter(v => v.level === 'A1'),
  A2: vocabularyData.filter(v => v.level === 'A2'),
  B1: vocabularyData.filter(v => v.level === 'B1'),
  B2: vocabularyData.filter(v => v.level === 'B2')
};

export const vocabularyByTheme = vocabularyData.reduce((acc, word) => {
  if (!acc[word.theme]) {
    acc[word.theme] = [];
  }
  acc[word.theme].push(word);
  return acc;
}, {} as Record<string, VocabWord[]>);

export const vocabularyByChapter = vocabularyData.reduce((acc, word) => {
  const key = word.level + '-K' + word.chapter;
  if (!acc[key]) {
    acc[key] = [];
  }
  acc[key].push(word);
  return acc;
}, {} as Record<string, VocabWord[]>);

export const vocabularyByType = vocabularyData.reduce((acc, word) => {
  if (!acc[word.type]) {
    acc[word.type] = [];
  }
  acc[word.type].push(word);
  return acc;
}, {} as Record<string, VocabWord[]>);
`;

fs.writeFileSync(OUTPUT_FILE, tsContent);
console.log(`\n✅ Written to ${OUTPUT_FILE}`);
console.log(`File size: ${(Buffer.byteLength(tsContent) / 1024).toFixed(1)} KB`);

// Stats
const byLevel = { A1: 0, A2: 0, B1: 0, B2: 0 };
finalVocab.forEach(v => {
  if (byLevel[v.level] !== undefined) byLevel[v.level]++;
});
console.log('By level:', byLevel);