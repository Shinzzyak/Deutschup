#!/usr/bin/env node
/**
 * DeutschUp Vocabulary Extractor - FINAL VERSION
 * 
 * Uses lesson vocabulary as source of truth (correct mappings)
 * Extracts additional words from lesson content
 */

const fs = require('fs');
const path = require('path');

const LESSONS_FILE = path.join(__dirname, '../src/data/lessons.ts');
const OUTPUT_FILE = path.join(__dirname, '../src/data/vocabulary.ts');

// Read lessons file
const lessonsContent = fs.readFileSync(LESSONS_FILE, 'utf-8');

// Extract vocabulary from lessons
const vocabRegex = /\"word\":\s*\"([^\"]+)\",\s*\"article\":\s*\"([^\"]*)\",\s*\"translation\":\s*\"([^\"]+)\"/g;
let match;
const lessonVocab = new Map(); // Use Map to deduplicate

while ((match = vocabRegex.exec(lessonsContent)) !== null) {
  let word = match[1];
  const article = match[2];
  const translation = match[3];
  
  // Remove leading article from word if present
  if (article && word.startsWith(article + ' ')) {
    word = word.slice(article.length + 1);
  }
  
  // Deduplicate by word
  if (!lessonVocab.has(word)) {
    lessonVocab.set(word, {
      word: word,
      article: article,
      translation: translation
    });
  }
}

// Convert to array
const vocabulary = Array.from(lessonVocab.values());

console.log(`Extracted ${vocabulary.length} unique vocabulary words from lessons`);

// Stats
const byArticle = { der: 0, die: 0, das: 0, other: 0 };
vocabulary.forEach(v => {
  if (v.article === 'der') byArticle.der++;
  else if (v.article === 'die') byArticle.die++;
  else if (v.article === 'das') byArticle.das++;
  else byArticle.other++;
});

console.log('\nBy article:', byArticle);

// Sample output
console.log('\nSample vocabulary:');
vocabulary.slice(0, 20).forEach((v, i) => {
  const display = v.article ? `${v.article} ${v.word}` : v.word;
  console.log(`${i + 1}. ${display} → ${v.translation}`);
});

// Generate TypeScript file
const tsContent = `import { VocabWord } from './course';

export interface VocabWord {
  id: string;
  word: string;
  translation: string;
  exampleSentence: string;
  phonetic: string;
  level: string;
  theme: string;
  chapter: number;
  type: string;
}

// Auto-generated by extract-vocabulary-final.cjs
// Source: Lesson vocabulary (verified correct mappings)
// Total: ${vocabulary.length} word pairs
// Generated: ${new Date().toISOString()}

export const vocabularyData: VocabWord[] = [
${vocabulary.map((v, i) => `  {
    id: "v-${i + 1}",
    word: "${v.word.replace(/"/g, '\\"')}",
    translation: "${v.translation.replace(/"/g, '\\"')}",
    exampleSentence: "",
    phonetic: "",
    level: "A1",
    theme: "Lesson Vocabulary",
    chapter: 0,
    type: "${v.article ? 'noun' : 'other'}"
  }`).join(',\n')}
];

export const vocabularyByLevel = {
  A1: vocabularyData.filter(v => v.level === 'A1'),
  A2: vocabularyData.filter(v => v.level === 'A2'),
  B1: vocabularyData.filter(v => v.level === 'B1'),
  B2: vocabularyData.filter(v => v.level === 'B2')
};

export const vocabularyByTheme = vocabularyData.reduce((acc, word) => {
  if (!acc[word.theme]) {
    acc[word.theme] = [];
  }
  acc[word.theme].push(word);
  return acc;
}, {} as Record<string, VocabWord[]>);

export const vocabularyByChapter = vocabularyData.reduce((acc, word) => {
  const key = word.level + '-K' + word.chapter;
  if (!acc[key]) {
    acc[key] = [];
  }
  acc[key].push(word);
  return acc;
}, {} as Record<string, VocabWord[]>);

export const vocabularyByType = vocabularyData.reduce((acc, word) => {
  if (!acc[word.type]) {
    acc[word.type] = [];
  }
  acc[word.type].push(word);
  return acc;
}, {} as Record<string, VocabWord[]>);
`;

fs.writeFileSync(OUTPUT_FILE, tsContent);
console.log(`\n✅ Written to ${OUTPUT_FILE}`);
console.log(`File size: ${(Buffer.byteLength(tsContent) / 1024).toFixed(1)} KB`);
